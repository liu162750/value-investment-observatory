import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {reviewDay,nextReviewDay,priceReview,weeklyMarketGate,POLICY} from '../scripts/mon-wed-policy.mjs';
const policySource=readFileSync(new URL('../scripts/mon-wed-policy.mjs',import.meta.url),'utf8').replace(/\r\n/g,'\n').replace(/export /g,'');
assert(readFileSync(new URL('../worker/dashboard.js',import.meta.url),'utf8').replace(/\r\n/g,'\n').includes(policySource),'服务器内嵌规则须与独立算法完全一致');
assert.equal(reviewDay(Date.parse('2026-11-02T14:59:00+08:00')),'2026-10-28');
assert.equal(reviewDay(Date.parse('2026-11-02T15:05:00+08:00')),'2026-11-02');
assert.equal(reviewDay(Date.parse('2026-11-04T14:59:00+08:00')),'2026-11-02');
assert.equal(reviewDay(Date.parse('2026-11-04T15:05:00+08:00')),'2026-11-04');
assert.equal(nextReviewDay(Date.parse('2026-11-02T15:05:00+08:00')),'2026-11-02 16:30');
const saved=JSON.parse(readFileSync(new URL('../worker/snapshot.json',import.meta.url),'utf8'));
const pinggao=saved.stocks.find(s=>s.symbol==='sh600312');
const review=priceReview(pinggao.rows,Date.parse('2026-11-04T20:30:00+08:00'),{symbol:'sh600312',legacyA:{date:'2026-11-04',low:18.6}});
assert.equal(review.policyId,POLICY);assert.equal(review.referenceDate,'2026-11-04');
assert.equal(review.trend,'上升趋势');assert.deepEqual(review.levels.slice(0,2),[[19.53,19.53],[18.60,18.60]]);
assert.throws(()=>priceReview(pinggao.rows.slice(-119),Date.parse('2026-11-04T20:30:00+08:00')),/120/);
const weeks=Array.from({length:20},(_,i)=>[new Date(Date.parse('2026-10-30')-(19-i)*7*86400000).toISOString().slice(0,10),'0',100]);
const now=Date.parse('2026-11-04T10:00:00+08:00');
assert.equal(weeklyMarketGate(weeks,now).status,'weak');
const improving=weeks.map(r=>[...r]);improving.at(-1)[2]=101;
assert.equal(weeklyMarketGate(improving,now).status,'strong');
assert.deepEqual(weeklyMarketGate(improving,now).allowedBuyTiers,[0,1]);
const between=weeks.map((r,i)=>[r[0],r[1],i<10?90:100]);between.at(-1)[2]=99;
assert.equal(weeklyMarketGate(between,now).status,'improving');
assert.deepEqual(weeklyMarketGate(between,now).allowedBuyTiers,[0,1]);
assert.deepEqual(weeklyMarketGate(weeks,now).allowedBuyTiers,[0]);
assert.equal(weeklyMarketGate(weeks.slice(1),now).status,'pending');
const backend=readFileSync(new URL('../worker/dashboard.js',import.meta.url),'utf8');
const screen=new Function(backend.slice(backend.indexOf('function evaluateFinancialTrend('),backend.indexOf('async function fundamentalTrend('))+';return evaluateFinancialTrend;')();
const finance=[{QDATE:'2026Q3',YSTZ:5,XSMLL:20},{QDATE:'2026Q2',YSTZ:8,XSMLL:20.2},{QDATE:'2026Q1',YSTZ:10,XSMLL:20.5}];
assert.equal(screen(finance).status,'screen-warning');
assert.equal(screen(finance).marginDecline,true,'毛利率下降幅度应为较早季度减最新季度');
assert.equal(screen(finance.slice(1)).status,'pending');
assert.equal(screen(finance.map((r,i)=>i===1?{...r,QDATE:'2025Q4'}:r)).status,'pending');
console.log('PASS: final Mon/Wed review, Pinggao confirmed starting levels and completed-week gate');
