assert.equal(screen(finance).marginDecline,true,'毛利率下降幅度应为较早季度减最新季度');
assert.equal(screen(finance.slice(1)).status,'pending');
assert.equal(screen(finance.map((r,i)=>i===1?{...r,QDATE:'2025Q4'}:r)).status,'pending');
